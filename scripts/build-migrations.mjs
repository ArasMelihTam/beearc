#!/usr/bin/env node
/**
 * Converts drizzle-kit's output (.sql files + journal) into a plain
 * TypeScript module, drizzle/migrations.ts, that the app imports directly.
 * This avoids any custom Babel/Metro config for bundling .sql files.
 *
 * Runs automatically as part of `npm run db:generate`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'drizzle');

const journal = JSON.parse(readFileSync(join(dir, 'meta', '_journal.json'), 'utf8'));

const entries = journal.entries.map((e, i) => ({
  key: `m${String(i).padStart(4, '0')}`,
  sql: readFileSync(join(dir, `${e.tag}.sql`), 'utf8'),
}));

const body = `// AUTO-GENERATED by scripts/build-migrations.mjs — do not edit by hand.
// Regenerate with: npm run db:generate

export default {
  journal: ${JSON.stringify(journal, null, 2).replace(/\n/g, '\n  ')},
  migrations: {
${entries.map((e) => `    ${e.key}: ${JSON.stringify(e.sql)},`).join('\n')}
  },
};
`;

writeFileSync(join(dir, 'migrations.ts'), body);
console.log(`Wrote drizzle/migrations.ts (${entries.length} migration(s)).`);
